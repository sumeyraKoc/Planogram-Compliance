"""
File:
    Merge Shelf Detection Results

Purpose:
    This script merges the product detection results obtained from multiple
    masked shelf images belonging to the same video frame into a single JSON
    file. Since each shelf is processed independently during product detection,
    this step consolidates all shelf-level detections into one frame-level
    result for easier analysis and downstream processing.

Input:
    - A directory containing product detection JSON files generated by the
      detect_products module.
    - Each subdirectory corresponds to a single video frame and contains one
      JSON file for each detected shelf.

Output:
    - One merged_result.json file for each video frame.
    - The merged file contains all shelf detection results associated with
      that frame.

Main Functionality:
    - Iterates through each frame directory.
    - Reads all shelf-level JSON files.
    - Combines the detections from different masked shelf images belonging to
      the same frame.
    - Stores the merged results in a single JSON file while preserving the
      individual shelf information.

Workflow:
    detect_shelves
            ↓
    get_masked_images
            ↓
    detect_products
            ↓
    Shelf-level product detections
            ↓
    Merge results (this script)
            ↓
    Frame-level merged_result.json

"""

import os
import json
from pathlib import Path
    
VIDEO_NAME = Path("config.txt").read_text(encoding="utf-8").strip()
INPUT_ROOT = fr"product_detection_results\{VIDEO_NAME}"
frame_dirs = sorted([
    d for d in os.listdir(INPUT_ROOT)
    if os.path.isdir(os.path.join(INPUT_ROOT, d))
])

for frame_name in frame_dirs:

    frame_dir = os.path.join(INPUT_ROOT, frame_name)

    merged = {
        "frame_name": frame_name,
        "shelves": []
    }

    json_files = sorted([
        f for f in os.listdir(frame_dir)
        if f.endswith(".json")
        and f != "merged_result.json"
    ])

    for json_file in json_files:

        json_path = os.path.join(frame_dir, json_file)

        with open(json_path, "r", encoding="utf-8") as f:
            shelf = json.load(f)

        merged["shelves"].append(shelf)

    save_path = os.path.join(
        frame_dir,
        "merged_result.json"
    )

    with open(save_path, "w", encoding="utf-8") as f:
        json.dump(
            merged,
            f,
            indent=4,
            ensure_ascii=False
        )

    print(f"Saved: {save_path}")

print("\nDone.")