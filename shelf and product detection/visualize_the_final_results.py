"""
File:
    Detection Visualization

Purpose:
    This script generates the final visualizations by combining the shelf region
    detections and product detection results on the original images. Shelf
    regions are highlighted with red polygons, while detected products are
    displayed with green bounding boxes. Each annotation is accompanied by
    descriptive labels, and a category summary showing the total number of
    detected products per category is displayed in the upper-right corner of
    the image.

Input:
    - Original images and shelf detection results generated by detect_shelves.
    - Product detection results (merged_result.json) generated after merging
      the outputs of detect_products.

Output:
    - Annotated images saved in the final_visualizations directory.
    - Each output image contains:
        - Red shelf region polygons
        - Green product bounding boxes
        - Product names
        - Product categories
        - Category-wise product count summary

Main Functionality:
    - Reads the original image.
    - Loads the detected shelf polygons.
    - Loads the merged product detection results.
    - Draws semi-transparent red polygons to visualize detected shelf regions.
    - Draws green bounding boxes around each detected product.
    - Displays the product name and category above each product.
    - Counts the number of detected products for each category.
    - Displays the category summary in the upper-right corner of the image.
    - Saves the final annotated visualization.

Visualization Details:
    - Shelf regions are shown as red semi-transparent polygons with red borders.
    - Product detections are shown as green bounding boxes.
    - Each product box is labeled with its product name and category.
    - The upper-right corner contains a summary listing all detected product
      categories and their corresponding counts.

Workflow:
    detect_shelves
            ↓
    get_masked_images
            ↓
    detect_products
            ↓
    merge_results
            ↓
    Visualization (this script)
            ↓
    Final annotated images
"""

import os
import json
from pathlib import Path
import cv2
import numpy as np
    
# --------------------------------------------------
# CONFIG
# --------------------------------------------------

VIDEO_NAME = Path("config.txt").read_text(encoding="utf-8").strip()

SHELF_RESULTS_FOLDER = fr"shelf_detection_results\{VIDEO_NAME}"

PRODUCT_RESULTS_FOLDER = (
    fr"product_detection_results\{VIDEO_NAME}"
)

OUTPUT_FOLDER = (
    fr"final_visualizations\{VIDEO_NAME}"
)

os.makedirs(OUTPUT_FOLDER, exist_ok=True)


# --------------------------------------------------
# Utils
# --------------------------------------------------

def polygon_to_pixels(polygon, width, height):

    pts = []

    for point in polygon:

        y, x = point

        px = int(x / 1000 * width)
        py = int(y / 1000 * height)

        pts.append([px, py])

    return np.array([pts], dtype=np.int32)


def bbox_to_pixels(bbox, width, height):

    ymin, xmin, ymax, xmax = bbox

    x1 = int(xmin / 1000 * width)
    y1 = int(ymin / 1000 * height)

    x2 = int(xmax / 1000 * width)
    y2 = int(ymax / 1000 * height)

    return x1, y1, x2, y2


# --------------------------------------------------
# Process All Frames
# --------------------------------------------------

image_files = sorted([
    f for f in os.listdir(SHELF_RESULTS_FOLDER)
    if f.lower().endswith((".jpg", ".jpeg", ".png"))
])

font = cv2.FONT_HERSHEY_SIMPLEX

for image_file in image_files:

    frame_name = os.path.splitext(image_file)[0]

    print(f"Processing {frame_name}")

    image_path = os.path.join(
        SHELF_RESULTS_FOLDER,
        image_file
    )

    shelf_json_path = os.path.join(
        SHELF_RESULTS_FOLDER,
        frame_name + ".json"
    )

    product_json_path = os.path.join(
        PRODUCT_RESULTS_FOLDER,
        frame_name,
        "merged_result.json"
    )

    if not os.path.exists(shelf_json_path):
        print(f" Shelf json not found: {frame_name}")
        continue

    if not os.path.exists(product_json_path):
        print(f" Product json not found: {frame_name}")
        continue

    img = cv2.imread(image_path)

    h, w = img.shape[:2]

    with open(shelf_json_path, "r", encoding="utf-8") as f:
        shelf_json = json.load(f)

    with open(product_json_path, "r", encoding="utf-8") as f:
        product_json = json.load(f)

    # --------------------------------------------------
    # Draw Shelf Polygons
    # --------------------------------------------------

    overlay = img.copy()

    for region in shelf_json["shelf_regions"]:

        pts = polygon_to_pixels(
            region["polygon"],
            w,
            h
        )

        cv2.fillPoly(
            overlay,
            pts,
            (0, 0, 255)
        )

    img = cv2.addWeighted(
        overlay,
        0.20,
        img,
        0.80,
        0
    )

    for region in shelf_json["shelf_regions"]:

        pts = polygon_to_pixels(
            region["polygon"],
            w,
            h
        )

        cv2.polylines(
            img,
            pts,
            True,
            (0, 0, 255),
            2
        )

    # --------------------------------------------------
    # Draw Products
    # --------------------------------------------------

    category_counter = {}

    for shelf in product_json["shelves"]:

        for product in shelf["products"]:

            x1, y1, x2, y2 = bbox_to_pixels(
                product["bbox"],
                w,
                h
            )

            category = product["category"]

            category_counter[category] = (
                category_counter.get(category, 0) + 1
            )

            cv2.rectangle(
                img,
                (x1, y1),
                (x2, y2),
                (0, 255, 0),
                2
            )

            cv2.putText(
                img,
                product["product_name"],
                (x1, max(20, y1 - 18)),
                font,
                0.45,
                (0, 255, 0),
                1,
                cv2.LINE_AA
            )

            cv2.putText(
                img,
                category,
                (x1, max(40, y1 - 3)),
                font,
                0.40,
                (255, 255, 0),
                1,
                cv2.LINE_AA
            )

    # --------------------------------------------------
    # Draw Category Summary
    # --------------------------------------------------

    lines = [
        f"{k}: {v}"
        for k, v in sorted(category_counter.items())
    ]

    if lines:

        box_width = 260
        line_height = 22
        box_height = line_height * len(lines) + 20

        x0 = w - box_width - 10
        y0 = 10

        overlay = img.copy()

        cv2.rectangle(
            overlay,
            (x0, y0),
            (x0 + box_width, y0 + box_height),
            (0, 0, 0),
            -1
        )

        img = cv2.addWeighted(
            overlay,
            0.60,
            img,
            0.40,
            0
        )

        y = y0 + 25

        for line in lines:

            cv2.putText(
                img,
                line,
                (x0 + 10, y),
                font,
                0.55,
                (255, 255, 255),
                1,
                cv2.LINE_AA
            )

            y += line_height

    # --------------------------------------------------
    # Save
    # --------------------------------------------------

    output_path = os.path.join(
        OUTPUT_FOLDER,
        image_file
    )

    cv2.imwrite(output_path, img)

    print(f" Saved -> {output_path}")

print("\nDone.")